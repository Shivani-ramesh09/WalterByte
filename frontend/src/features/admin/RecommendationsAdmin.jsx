import { useState } from 'react'
import { api, useApi } from '../../lib/api'
import { Empty, ErrorBox, Loading } from '../../components/ui'
import { PeriodPicker, SyntheticBanner, day } from './adminUi'

const REVIEW = { reviewed: 'Reviewed', accepted: 'Accepted', dismissed: 'Dismissed', more_info: 'Needs more information' }

export function RecommendationsAdmin({ ctx }) {
  const { data, loading, error, reload } = useApi(`/admin/recommendations?${ctx.query}`)
  const [filter, setFilter] = useState('open')
  const recs = (data?.recommendations || []).filter((r) => filter === 'all' || (filter === 'open' ? !r.review || r.review.status === 'more_info' : r.review))
  return (
    <>
      <h2>Recommendations</h2>
      <PeriodPicker value={ctx.days} onChange={ctx.setDays} />
      <p className="muted small">
        Generated by fixed, explainable rules from recorded Explore and Connect data. They suggest what to look at; they never approve budgets or purchases.
      </p>
      <div className="chips" role="group" aria-label="Filter recommendations">
        {[['open', 'Awaiting review'], ['done', 'Reviewed'], ['all', 'All']].map(([k, label]) => (
          <button key={k} type="button" className={filter === k ? 'chip selected' : 'chip'} aria-pressed={filter === k} onClick={() => setFilter(k)}>{label}</button>
        ))}
      </div>
      {loading && <Loading />}
      <ErrorBox error={error} onRetry={reload} />
      {data && <SyntheticBanner show={data.synthetic} />}
      {data && !recs.length && <Empty title="Nothing here" text="No recommendations match this filter for the period." />}
      {recs.map((r) => <RecommendationCard key={r.id} rec={r} onSaved={() => reload(true)} />)}
    </>
  )
}

function RecommendationCard({ rec, onSaved }) {
  const [note, setNote] = useState(rec.review?.note || '')
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState(null)
  const review = async (status) => {
    setBusy(true)
    setError(null)
    try {
      await api(`/admin/recommendations/${encodeURIComponent(rec.id)}`, { method: 'PATCH', body: { status, note } })
      onSaved()
    } catch (err) {
      setError(err)
    } finally {
      setBusy(false)
    }
  }
  return (
    <article className="card rec stack-sm">
      <div className="card-row">
        <span className="tag">{rec.module === 'connect' ? 'Connect' : 'Explore'}</span>
        <span className={`evidence evidence-${rec.evidence}`} title="Evidence quality">{rec.evidence} evidence</span>
      </div>
      <h3>{rec.title}</h3>
      <p><span className="kind kind-observed">observed</span> {rec.observation}</p>
      <small className="muted">Period: {rec.period}</small>
      <dl className="metric-list">
        {rec.metrics.map((m) => (
          <div key={m.label}><dt>{m.label}</dt><dd>{m.value}</dd></div>
        ))}
      </dl>
      <div>
        <strong className="small">Limitations</strong>
        <ul className="small muted">{rec.limitations.map((l) => <li key={l}>{l}</li>)}</ul>
      </div>
      <p><span className="kind kind-recommendation">suggested next step</span> {rec.action}</p>
      {rec.review && (
        <p className="small muted">
          {REVIEW[rec.review.status]} on {day(rec.review.reviewedAt)}{rec.review.note ? `: ${rec.review.note}` : ''}
        </p>
      )}
      <input className="input" placeholder="Note (optional)" maxLength={1000} value={note} onChange={(e) => setNote(e.target.value)} aria-label="Review note" />
      <ErrorBox error={error} />
      <div className="row wrap">
        {Object.entries(REVIEW).map(([status, label]) => (
          <button key={status} className={rec.review?.status === status ? 'btn small primary' : 'btn small'} disabled={busy} onClick={() => review(status)}>{label}</button>
        ))}
      </div>
    </article>
  )
}
